#!/usr/bin/env bash

set -euo pipefail

REPO_DIR=$(git rev-parse --show-toplevel)

# can't find the file because of the ENV var
# shellcheck source=/dev/null
source "$REPO_DIR/fuzz/fuzz-util.sh"

# 1. Generate fuzz/Cargo.toml
cat > "$REPO_DIR/fuzz/Cargo.toml" <<EOF
[package]
name = "tidecoin-fuzz"
edition = "2021"
rust-version = "1.94.1"
version = "0.0.1"
authors = ["Generated by fuzz/generate-files.sh"]
publish = false

[package.metadata]
cargo-fuzz = true

[features]
node-oracle = ["dep:node_parity", "dep:consensus_core", "dep:rand_chacha"]

[dependencies]
rand_chacha = { version = "0.3.1", optional = true }
node_parity = { package = "tidecoin-node-parity", path = "../node-parity", optional = true }
consensus_core = { package = "tidecoin-consensus-core", path = "../consensus-core", optional = true }
consensus = { path = "../consensus" }
tidecoin = { path = "../tidecoin", package = "tidecoin", features = [ "serde", "arbitrary" ] }
tidecoin_consensus_encoding = { path = "../consensus_encoding", package = "tidecoin-consensus-encoding" }
p2p = { path = "../p2p", package = "tidecoin-p2p-messages", features = ["arbitrary"] }

arbitrary = { version = "1.4.1" }
libfuzzer-sys = { version = "0.4.0" }
serde = { version = "1.0.195", features = [ "derive" ] }
serde_json = "1.0.68"
standard_test = "0.1.0"

[lints.rust]
unexpected_cfgs = { level = "deny", check-cfg = ['cfg(fuzzing)'] }

[lints.clippy]
redundant_clone = "warn"
use_self = "warn"
EOF

for targetFile in $(listTargetFiles); do
    targetName=$(targetFileToName "$targetFile")
    cat >> "$REPO_DIR/fuzz/Cargo.toml" <<EOF

[[bin]]
name = "$targetName"
path = "$targetFile"
test = false
doc = false
bench = false
EOF
done

cat >> "$REPO_DIR/fuzz/Cargo.toml" <<'EOF'

[package.metadata.rbmt.lint]
allowed_duplicates = ["block-buffer", "cpufeatures", "crypto-common", "digest", "getrandom", "keccak", "libc", "rand_core", "sha3", "syn"]
EOF

# 2. Generate .github/workflows/fuzz.yml
cat > "$REPO_DIR/.github/workflows/fuzz.yml" <<EOF
# Automatically generated by fuzz/generate-files.sh
name: Fuzz
on:
  # Manual only: run from the Actions tab when wanted.
  workflow_dispatch:
permissions: {}

jobs:
  fuzz:
    if: \${{ !github.event.act }}
    runs-on: ubuntu-24.04
    permissions:
      contents: read
    strategy:
      fail-fast: false
      matrix:
        # One job per fuzz target, each running fuzz/fuzz.sh (100,000 inputs).
        fuzz_target: [
$(for name in $(cargo fuzz list | grep -v "^consensus_node_differential$"); do echo "          $name,"; done)
        ]
    steps:
      - name: Install test dependencies
        run: sudo apt-get update -y && sudo apt-get install -y binutils-dev libunwind8-dev libcurl4-openssl-dev libelf-dev libdw-dev cmake gcc libiberty-dev
      - uses: actions/checkout@08c6903cd8c0fde910a37f88322edcfb5dd907a8 # v5.0.0
        with:
          persist-credentials: false
      - uses: actions/cache@0057852bfaa89a56745cba8c7296529d2fc39830 # v4.3.0
        id: cache-fuzz
        with:
          path: |
            ~/.cargo/bin
            fuzz/target
            target
          key: cache-\${{ matrix.target }}-\${{ hashFiles('**/Cargo.toml','**/Cargo.lock') }}
      - uses: dtolnay/rust-toolchain@5d458579430fc14a04a08a1e7d3694f545e91ce6 # stable
        with:
          toolchain: '1.94.1'
      - name: fuzz
        run: |
          if [[ "\${{ matrix.fuzz_target }}" =~ ^tidecoin ]]; then
              export RUSTFLAGS='--cfg=hashes_fuzz'
          fi
          echo "Using RUSTFLAGS \$RUSTFLAGS"
          cd fuzz && ./fuzz.sh "\${{ matrix.fuzz_target }}"
      - run: echo "\${{ matrix.fuzz_target }}" >executed_\${{ matrix.fuzz_target }}
      - uses: actions/upload-artifact@330a01c490aca151604b8cf639adc76d48f6c5d4 # v5.0.0
        with:
          name: executed_\${{ matrix.fuzz_target }}
          path: executed_\${{ matrix.fuzz_target }}

  verify-execution:
    if: \${{ !github.event.act }}
    needs: fuzz
    runs-on: ubuntu-24.04
    permissions:
      contents: read
    steps:
      - uses: actions/checkout@08c6903cd8c0fde910a37f88322edcfb5dd907a8 # v5.0.0
        with:
          persist-credentials: false
      - uses: actions/download-artifact@018cc2cf5baa6db3ef3c5f8a56943fffe632ef53 # v6.0.0
      - name: Display structure of downloaded files
        run: ls -R
      - run: find executed_* -type f -exec cat {} + | sort > executed
      - run: cargo fuzz list | grep -v "^consensus_node_differential$" | sort | diff - executed
EOF
